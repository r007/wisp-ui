/**
 * Emits the global, scheme-aware system tokens (`--md-sys-*`, `--md-ref-*`).
 *
 * This is the only stylesheet an app has to load for every component, so it
 * stays deliberately small: colour roles, type scale, shape, elevation, state
 * and motion. Component tokens are emitted per component instead.
 */

import { customProperty, ms, num, px, rem } from './css.ts';
import { pathToLinearEasing } from './linear-easing.ts';
import { springToLinearEasing } from './spring.ts';
import type { TokenDatabase, TokenValue } from './types.ts';

export interface SystemCssOptions {
  /** Cascade layer the stylesheet is declared in. */
  layer: string;
}

/**
 * Typeface per type style. Upstream's current data dropped this mapping and
 * lists a literal family on every style, so it is carried over from Material's
 * published type scale: display, headline and title-large use the brand face.
 */
const BRAND_STYLES = /^(?:emphasized\.)?(?:display|headline)-|^(?:emphasized\.)?title-large$/;

const FALLBACK_STACK = 'system-ui, -apple-system, "Segoe UI", sans-serif';

export function emitSystemCss(db: TokenDatabase, options: SystemCssOptions): string {
  const blocks = [
    rootBlock(db),
    `[data-wisp-motion='standard'] {\n${springDeclarations(db, 'standard')}\n}`,
    ...contrastBlocks(db),
  ];

  return [banner(db), `@layer ${options.layer} {`, indent(blocks.join('\n\n')), '}', ''].join('\n');
}

/** The colour roles of the Material system, as a typed constant for runtime theming. */
export function emitColorRoles(db: TokenDatabase): string {
  const roles = Object.keys(db.schemes.color.light ?? {}).map((name) =>
    name.replace('md.sys.color.', ''),
  );
  return [
    '// Generated by @wisp-ui/codegen. Do not edit by hand.',
    '',
    `export const COLOR_ROLES = [`,
    ...roles.map((role) => `  '${role}',`),
    '] as const;',
    '',
    'export type ColorRole = (typeof COLOR_ROLES)[number];',
    '',
  ].join('\n');
}

function banner(db: TokenDatabase): string {
  const { repository, commit, tokenVersion } = db.meta;
  return [
    '/* Material 3 Expressive system tokens.',
    ' *',
    ` * Generated by @wisp-ui/codegen from Material tokens v${tokenVersion}`,
    ` * (${repository} @ ${commit.slice(0, 9)}). Do not edit by hand. */`,
    '',
  ].join('\n');
}

function rootBlock(db: TokenDatabase): string {
  const sections: Array<[string, string[]]> = [
    ['Colour: light-dark() follows `color-scheme`, so any subtree can flip', colorDeclarations(db)],
    ['Typography', typographyDeclarations(db)],
    ['Shape', shapeDeclarations(db)],
    ['Elevation', elevationDeclarations(db)],
    ['State', stateDeclarations(db)],
    ['Motion', motionDeclarations(db)],
    [
      'Motion: springs (Expressive scheme; opt out with data-wisp-motion="standard")',
      springLines(db, 'expressive'),
    ],
  ];

  const body = sections
    .map(([title, lines]) => [`/* ${title} */`, ...lines].map((l) => indent(l)).join('\n'))
    .join('\n\n');
  return `:root {\n  color-scheme: light dark;\n\n${body}\n}`;
}

// ── Colour ──────────────────────────────────────────────────────────────────

function hex(value: TokenValue | undefined, role: string): string {
  if (value?.type !== 'hex') throw new Error(`Colour role ${role} is not a literal colour`);
  return value.value;
}

function colorDeclarations(db: TokenDatabase): string[] {
  const light = db.schemes.color.light ?? {};
  const dark = db.schemes.color.dark ?? {};
  return Object.keys(light).map((name) => {
    const a = hex(light[name], name);
    const b = hex(dark[name], name);
    return `${customProperty(name)}: ${a === b ? a : `light-dark(${a}, ${b})`};`;
  });
}

/**
 * Higher-contrast schemes only restate roles that change, so each block
 * overrides just those and inherits the rest.
 *
 * The operating system's preference maps onto the high scheme: `prefers-contrast: more` applies
 * it to the root, unless the app has chosen a level itself (`data-wisp-contrast` on `<html>`,
 * whatever its value, `standard` included), so an explicit choice always wins. The extra
 * `:not()` also makes this rule more specific than the root's own colours, which come first.
 */
function contrastBlocks(db: TokenDatabase): string[] {
  const declarations = (level: 'medium' | 'high') => {
    const light = db.schemes.color[`light-${level}-contrast`] ?? {};
    const dark = db.schemes.color[`dark-${level}-contrast`] ?? {};
    const names = [...new Set([...Object.keys(light), ...Object.keys(dark)])].sort();
    return names.map((name) => {
      const a = hex(light[name] ?? db.schemes.color.light?.[name], name);
      const b = hex(dark[name] ?? db.schemes.color.dark?.[name], name);
      return `  ${customProperty(name)}: ${a === b ? a : `light-dark(${a}, ${b})`};`;
    });
  };
  const blocks = (['medium', 'high'] as const).map(
    (level) => `[data-wisp-contrast='${level}'] {\n${declarations(level).join('\n')}\n}`,
  );
  const system = declarations('high')
    .map((line) => `  ${line}`)
    .join('\n');
  return [
    ...blocks,
    `@media (prefers-contrast: more) {\n  :root:not([data-wisp-contrast]) {\n${system}\n  }\n}`,
  ];
}

// ── Typography ──────────────────────────────────────────────────────────────

function typographyDeclarations(db: TokenDatabase): string[] {
  const lines: string[] = [];
  for (const family of ['brand', 'plain'] as const) {
    const name = db.tokens[`md.ref.typeface.${family}`];
    if (name?.type !== 'string') throw new Error(`Missing typeface ${family}`);
    lines.push(`--md-ref-typeface-${family}: ${name.value}, ${FALLBACK_STACK};`);
  }

  for (const [token, value] of Object.entries(db.tokens)) {
    const style = token.startsWith('md.sys.typescale.') && token.slice('md.sys.typescale.'.length);
    if (!style || value.type !== 'typescale') continue;
    const family = BRAND_STYLES.test(style) ? 'brand' : 'plain';
    const property = customProperty(token);
    lines.push(
      `${property}: ${value.weight} ${rem(value.size)}/${rem(value.lineHeight)} var(--md-ref-typeface-${family});`,
      `${property}-tracking: ${rem(value.tracking)};`,
    );
  }
  return lines;
}

// ── Shape ───────────────────────────────────────────────────────────────────

/** Radius used for the "circular" family where a real half-height is unknown. */
const FULL_RADIUS = '9999px';

function shapeDeclarations(db: TokenDatabase): string[] {
  const lines: string[] = [];
  for (const [token, value] of Object.entries(db.tokens)) {
    if (!token.startsWith('md.sys.shape.')) continue;
    if (value.type === 'number') lines.push(`${customProperty(token)}: ${px(value.value)};`);
    else if (value.type === 'shape')
      lines.push(`${customProperty(token)}: ${cornerRadius(value)};`);
  }
  return lines;
}

export function cornerRadius(
  shape: Extract<TokenValue, { type: 'shape' }>,
  circular = FULL_RADIUS,
): string {
  if (shape.family === 'circular') return circular;
  const [tl, tr, br, bl] = shape.corners;
  return tl === tr && tr === br && br === bl
    ? px(tl)
    : shape.corners.map((corner) => px(corner)).join(' ');
}

// ── Elevation ───────────────────────────────────────────────────────────────

const clamp = (min: number, value: number, max: number) => Math.min(max, Math.max(min, value));

/**
 * Material renders elevation as a *key* and an *ambient* shadow whose offset,
 * blur and spread grow with the level. These curves are the closed form used
 * by material-web (Apache-2.0), which reproduces the published level 1–5
 * shadows exactly and keeps a stable number of shadows so levels interpolate.
 */
export function elevationShadow(level: number): string {
  const keyY = clamp(0, level, 1) + clamp(0, level - 3, 1) + 2 * clamp(0, level - 4, 1);
  const keyBlur = 2 * clamp(0, level, 1) + clamp(0, level - 2, 1) + clamp(0, level - 4, 1);
  const ambientY = clamp(0, level, 1) + clamp(0, level - 1, 1) + 2 * clamp(0, level - 2, 3);
  const ambientBlur = 3 * clamp(0, level, 2) + 2 * clamp(0, level - 2, 3);
  const ambientSpread = clamp(0, level, 4) + 2 * clamp(0, level - 4, 1);

  const shadow = (opacity: number) =>
    `color-mix(in srgb, var(--md-sys-color-shadow) ${opacity}%, transparent)`;
  return [
    `0 ${px(keyY)} ${px(keyBlur)} 0 ${shadow(30)}`,
    `0 ${px(ambientY)} ${px(ambientBlur)} ${px(ambientSpread)} ${shadow(15)}`,
  ]
    .join(', ')
    .replaceAll(/\b0px\b/g, '0');
}

/** Elevation in dp → level index, from `md.sys.elevation.level*`. */
export function elevationLevels(db: TokenDatabase): Map<number, number> {
  const levels = new Map<number, number>();
  for (const [token, value] of Object.entries(db.tokens)) {
    const level = /^md\.sys\.elevation\.level(\d)$/.exec(token)?.[1];
    if (level && value.type === 'number') levels.set(value.value, Number(level));
  }
  if (levels.size === 0) throw new Error('No md.sys.elevation.level* tokens found');
  return levels;
}

function elevationDeclarations(db: TokenDatabase): string[] {
  return [...elevationLevels(db).values()]
    .sort((a, b) => a - b)
    .map((level) => `--md-sys-elevation-level${level}: ${elevationShadow(level)};`);
}

// ── State ───────────────────────────────────────────────────────────────────

function stateDeclarations(db: TokenDatabase): string[] {
  const lines: string[] = [];
  for (const [token, value] of Object.entries(db.tokens)) {
    if (!token.startsWith('md.sys.state.') || value.type !== 'number') continue;
    const unit = token.endsWith('opacity') ? num(value.value) : px(value.value);
    lines.push(`${customProperty(token)}: ${unit};`);
  }
  return lines;
}

// ── Motion ──────────────────────────────────────────────────────────────────

function motionDeclarations(db: TokenDatabase): string[] {
  const lines: string[] = [];
  for (const [token, value] of Object.entries(db.tokens)) {
    if (!token.startsWith('md.sys.motion.')) continue;
    const property = customProperty(token);
    if (value.type === 'duration') lines.push(`${property}: ${ms(value.ms)};`);
    else if (value.type === 'cubic-bezier') {
      lines.push(`${property}: cubic-bezier(${value.points.map((p) => num(p)).join(', ')});`);
    } else if (token.includes('.easing.') && value.type === 'string') {
      lines.push(`${property}: ${pathToLinearEasing(value.value, 0.005)};`);
    }
  }
  return lines;
}

const SPRING_NAMES = /^md\.sys\.motion\.spring\.(default|fast|slow)\.(effects|spatial)\.stiffness$/;

/**
 * Each named spring becomes one variable holding `<duration> linear(…)`, ready
 * for `transition: transform var(--md-sys-motion-spring-fast-spatial)`.
 */
function springLines(db: TokenDatabase, scheme: 'standard' | 'expressive'): string[] {
  const set = db.schemes.motion[scheme] ?? {};
  const number = (name: string) => {
    const value = set[name];
    if (value?.type !== 'number') throw new Error(`Missing spring token ${name} in ${scheme}`);
    return value.value;
  };
  return Object.keys(set)
    .filter((name) => SPRING_NAMES.test(name))
    .sort()
    .map((stiffnessToken) => {
      const base = stiffnessToken.replace(/\.stiffness$/, '');
      const spring = springToLinearEasing({
        stiffness: number(stiffnessToken),
        damping: number(`${base}.damping`),
      });
      return `${customProperty(base)}: ${spring.css};`;
    });
}

function springDeclarations(db: TokenDatabase, scheme: 'standard' | 'expressive'): string {
  return springLines(db, scheme).map(indent).join('\n');
}

function indent(text: string): string {
  return text
    .split('\n')
    .map((line) => (line ? `  ${line}` : line))
    .join('\n');
}
